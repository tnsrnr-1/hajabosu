"""DB 연결과 저장은 이 파일에서만 한다. 연결 정보는 .env의 DATABASE_URL 한 줄 (웹 배포는 Secrets)."""
import os
import sys
from pathlib import Path

import pandas as pd
from dotenv import load_dotenv
from sqlalchemy import create_engine, text

BASE = Path(__file__).resolve().parent
load_dotenv(BASE / ".env")

LEDGER_COLUMNS = [
    "접수번호", "접수일", "원문파일", "위치", "공종", "하자내용", "긴급도", "조치기한",
    "공사번호", "시공업체", "준공일", "보증만료일", "보증판정", "책임구분", "상태", "비고",
]

_engine = None


def _database_url() -> str:
    url = (os.getenv("DATABASE_URL") or "").strip().strip('"').strip("'")
    if not url:
        try:  # 웹 배포(Streamlit Cloud)에서는 Secrets에서 읽는다
            import streamlit as st

            url = str(st.secrets.get("DATABASE_URL", "")).strip()
        except Exception:
            url = ""
    if not url:
        raise SystemExit(
            "[안내] DATABASE_URL이 없습니다.\n"
            "  Supabase > Connect > Session pooler 주소를 .env의 DATABASE_URL= 뒤에 붙여넣고 저장하세요."
        )
    if "[YOUR-PASSWORD]" in url:
        raise SystemExit("[안내] DATABASE_URL의 [YOUR-PASSWORD]를 DB 비밀번호로 바꿔 저장하세요.")
    if url.startswith("postgres://"):
        url = "postgresql://" + url[len("postgres://"):]
    if url.startswith("postgresql://"):
        url = "postgresql+psycopg://" + url[len("postgresql://"):]
    return url


def engine():
    global _engine
    if _engine is None:
        _engine = create_engine(_database_url(), pool_pre_ping=True)
    return _engine


def _q(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


# ---------- 표 만들기 ----------
def init() -> None:
    """처음 실행하면 접수·하자대장 표를 만들고 RLS를 켠다. 여러 번 실행해도 안전."""
    ledger_cols = ",\n  ".join(
        f"{_q(c)} text" + (" PRIMARY KEY" if c == "접수번호" else "") for c in LEDGER_COLUMNS
    )
    with engine().begin() as con:
        con.execute(text("""
            CREATE TABLE IF NOT EXISTS "접수" (
              id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              "접수일시" timestamptz NOT NULL DEFAULT now(),
              "발견일" date NOT NULL,
              "접수자" text NOT NULL,
              "부서" text,
              "위치" text,
              "내용" text NOT NULL,
              "처리상태" text NOT NULL DEFAULT '미처리'
                CHECK ("처리상태" IN ('미처리', '처리완료')),
              "접수번호" text
            )"""))
        con.execute(text(f'CREATE TABLE IF NOT EXISTS "하자대장" (\n  {ledger_cols}\n)'))
        con.execute(text('ALTER TABLE "접수" ENABLE ROW LEVEL SECURITY'))
        con.execute(text('ALTER TABLE "하자대장" ENABLE ROW LEVEL SECURITY'))


# ---------- 하자대장 ----------
def load_ledger() -> pd.DataFrame:
    init()
    cols = ", ".join(_q(c) for c in LEDGER_COLUMNS)
    with engine().connect() as con:
        df = pd.read_sql(text(f'SELECT {cols} FROM "하자대장" ORDER BY "접수번호"'), con)
    return df.fillna("").astype(str)[LEDGER_COLUMNS]


def save_ledger(df: pd.DataFrame) -> None:
    """접수번호 기준으로 넣거나 고친다 (upsert)."""
    init()
    cols = ", ".join(_q(c) for c in LEDGER_COLUMNS)
    params = ", ".join(f":p{i}" for i in range(len(LEDGER_COLUMNS)))
    updates = ", ".join(f"{_q(c)} = EXCLUDED.{_q(c)}" for c in LEDGER_COLUMNS[1:])
    sql = text(
        f'INSERT INTO "하자대장" ({cols}) VALUES ({params}) '
        f'ON CONFLICT ("접수번호") DO UPDATE SET {updates}'
    )
    rows = [
        {f"p{i}": str(r[c]) if pd.notna(r[c]) else "" for i, c in enumerate(LEDGER_COLUMNS)}
        for _, r in df.iterrows()
    ]
    if rows:
        with engine().begin() as con:
            con.execute(sql, rows)


def counts() -> dict:
    init()
    with engine().connect() as con:
        return {t: con.execute(text(f"SELECT count(*) FROM {_q(t)}")).scalar() for t in ("접수", "하자대장")}


def import_csv(path=BASE / "data" / "하자대장.csv") -> int:
    """data/하자대장.csv를 DB로 옮긴다 (한 번만 하면 되지만 다시 해도 중복되지 않음)."""
    df = pd.read_csv(path, encoding="utf-8-sig", dtype=str).fillna("")
    save_ledger(df)
    return len(df)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    init()
    n = import_csv()
    print(f"하자대장.csv {n}건을 DB로 옮겼습니다.")
    for t, c in counts().items():
        print(f"  {t}: {c}건")
